#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Entry AB test after clean 10-day hold above MA120.

Input is the clean_hold10_events.csv generated by ma120_hold10_feature_study.py.
The sell rule is fixed: exit at the last close before the stock falls below
MA120, using the already-labeled future_end_date from the input event.
"""

from __future__ import annotations

import argparse
import glob
import os
from datetime import datetime
from typing import Dict, Iterable, List, Optional

import numpy as np
import pandas as pd


def symbol_from_path(path: str) -> str:
    return os.path.basename(path).split("_", 1)[0]


def scan_symbol_files(csv_dir: str, symbols: Iterable[str]) -> Dict[str, List[str]]:
    need = set(symbols)
    grouped: Dict[str, List[str]] = {s: [] for s in need}
    for fp in glob.glob(os.path.join(csv_dir, "**", "*"), recursive=True):
        if not os.path.isfile(fp):
            continue
        sym = symbol_from_path(fp)
        if sym in need:
            grouped[sym].append(fp)
    return {k: v for k, v in grouped.items() if v}


def parse_date(raw: pd.Series) -> pd.Series:
    s = raw.astype(str)
    if s.str.fullmatch(r"\d{8}").mean() > 0.8:
        return pd.to_datetime(s, format="%Y%m%d", errors="coerce")
    return pd.to_datetime(s, errors="coerce")


def load_symbol(paths: Iterable[str]) -> pd.DataFrame:
    frames: List[pd.DataFrame] = []
    for fp in paths:
        try:
            df = pd.read_csv(fp)
        except Exception:
            continue
        if "close" not in df.columns:
            continue
        dcol = "date" if "date" in df.columns else ("Unnamed: 0" if "Unnamed: 0" in df.columns else None)
        if dcol is None:
            continue
        tmp = df.copy()
        tmp["dt"] = parse_date(tmp[dcol])
        for c in ["open", "high", "low", "close"]:
            if c in tmp.columns:
                tmp[c] = pd.to_numeric(tmp[c], errors="coerce")
        keep = [c for c in ["dt", "open", "high", "low", "close"] if c in tmp.columns]
        frames.append(tmp[keep])
    if not frames:
        return pd.DataFrame()
    out = pd.concat(frames, ignore_index=True)
    out = out.dropna(subset=["dt", "close"]).sort_values("dt")
    out = out.drop_duplicates(subset=["dt"], keep="last").reset_index(drop=True)
    out["ma20"] = out["close"].rolling(20, min_periods=20).mean()
    out["ma120"] = out["close"].rolling(120, min_periods=120).mean()
    return out


def row_idx_on_or_after(k: pd.DataFrame, dt: pd.Timestamp) -> Optional[int]:
    idx = k.index[k["dt"] >= dt]
    return int(idx[0]) if len(idx) else None


def row_idx_on_or_before(k: pd.DataFrame, dt: pd.Timestamp) -> Optional[int]:
    idx = k.index[k["dt"] <= dt]
    return int(idx[-1]) if len(idx) else None


def calc_trade(
    event: pd.Series,
    k: pd.DataFrame,
    entry_idx: Optional[int],
    entry_name: str,
    base_buy_idx: int,
    exit_idx: int,
) -> Dict[str, object]:
    row = {
        "symbol": event["symbol"],
        "break_date": event["break_date"],
        "buy_base_date": event["buy_date"],
        "entry_rule": entry_name,
        "triggered": False,
        "wait_days": np.nan,
        "entry_date": pd.NaT,
        "exit_date": pd.NaT,
        "entry_price": np.nan,
        "exit_price": np.nan,
        "ret": np.nan,
        "max_ret": np.nan,
        "max_drawdown": np.nan,
        "future_above_ma120_days": event.get("future_above_ma120_days", np.nan),
    }
    if entry_idx is None or entry_idx > exit_idx or entry_idx >= len(k):
        return row
    entry = float(k.at[entry_idx, "close"])
    if entry <= 0:
        return row
    path = k.iloc[entry_idx : exit_idx + 1].copy()
    if path.empty:
        return row
    row.update(
        {
            "triggered": True,
            "wait_days": int(entry_idx - base_buy_idx),
            "entry_date": k.at[entry_idx, "dt"],
            "exit_date": k.at[exit_idx, "dt"],
            "entry_price": entry,
            "exit_price": float(k.at[exit_idx, "close"]),
            "ret": float(k.at[exit_idx, "close"] / entry - 1.0),
            "max_ret": float(path["close"].max() / entry - 1.0),
            "max_drawdown": float((path["close"] / entry - 1.0).min()),
        }
    )
    return row


def find_entries(event: pd.Series, k: pd.DataFrame, lookahead: int) -> List[tuple[str, Optional[int]]]:
    break_i = row_idx_on_or_after(k, pd.Timestamp(event["break_date"]))
    base_i = row_idx_on_or_after(k, pd.Timestamp(event["buy_date"]))
    exit_i = row_idx_on_or_before(k, pd.Timestamp(event["future_end_date"]))
    if break_i is None or base_i is None or exit_i is None:
        return []

    p0 = float(k.at[break_i, "close"])
    obs_high = float(k.iloc[break_i:base_i]["close"].max()) if base_i > break_i else p0
    end = min(exit_i, base_i + lookahead)
    window = k.iloc[base_i : end + 1]

    entries: List[tuple[str, Optional[int]]] = [("direct_day11", base_i)]

    def first_idx(mask: pd.Series) -> Optional[int]:
        hit = mask[mask].index
        return int(hit[0]) if len(hit) else None

    entries.append(
        (
            "pullback_ma120_3pct",
            first_idx((window["close"] > window["ma120"]) & (window["close"] / window["ma120"] - 1.0 <= 0.03)),
        )
    )
    entries.append(
        (
            "pullback_p0_3pct",
            first_idx((window["close"] > window["ma120"]) & (window["close"] <= p0 * 1.03)),
        )
    )
    entries.append(
        (
            "pullback_ma20_2pct",
            first_idx(
                (window["close"] > window["ma120"])
                & pd.notna(window["ma20"])
                & (window["close"] / window["ma20"] - 1.0 <= 0.02)
            ),
        )
    )
    entries.append(("break_obs_high", first_idx(window["close"] > obs_high)))
    return entries


def summarize(trades: pd.DataFrame, total_events: int) -> pd.DataFrame:
    rows: List[Dict[str, object]] = []
    for rule, sub in trades.groupby("entry_rule"):
        hit = sub[sub["triggered"]].copy()
        rows.append(
            {
                "entry_rule": rule,
                "total_events": total_events,
                "triggered": int(len(hit)),
                "trigger_rate": float(len(hit) / total_events) if total_events else np.nan,
                "avg_wait_days": float(hit["wait_days"].mean()) if len(hit) else np.nan,
                "avg_ret": float(hit["ret"].mean()) if len(hit) else np.nan,
                "median_ret": float(hit["ret"].median()) if len(hit) else np.nan,
                "win_rate": float((hit["ret"] > 0).mean()) if len(hit) else np.nan,
                "tail_gt20": float((hit["ret"] >= 0.20).mean()) if len(hit) else np.nan,
                "loss_lt10": float((hit["ret"] <= -0.10).mean()) if len(hit) else np.nan,
                "avg_max_ret": float(hit["max_ret"].mean()) if len(hit) else np.nan,
                "avg_max_drawdown": float(hit["max_drawdown"].mean()) if len(hit) else np.nan,
                "missed_true60": int(((~sub["triggered"]) & (sub["future_above_ma120_days"] >= 60)).sum()),
                "missed_true60_rate": float(((~sub["triggered"]) & (sub["future_above_ma120_days"] >= 60)).sum() / total_events)
                if total_events
                else np.nan,
            }
        )
    return pd.DataFrame(rows).sort_values("entry_rule")


def stability(trades: pd.DataFrame, total_events_by_period: pd.Series) -> pd.DataFrame:
    t = trades.copy()
    y = pd.to_datetime(t["buy_base_date"]).dt.year
    t["period"] = np.select(
        [y <= 2018, (y >= 2019) & (y <= 2022), y >= 2023],
        ["2014-2018", "2019-2022", "2023-2026"],
        default="other",
    )
    rows = []
    for (period, rule), sub in t[t["period"] != "other"].groupby(["period", "entry_rule"]):
        total = int(total_events_by_period.get(period, 0))
        hit = sub[sub["triggered"]]
        rows.append(
            {
                "period": period,
                "entry_rule": rule,
                "total_events": total,
                "triggered": int(len(hit)),
                "trigger_rate": float(len(hit) / total) if total else np.nan,
                "avg_ret": float(hit["ret"].mean()) if len(hit) else np.nan,
                "median_ret": float(hit["ret"].median()) if len(hit) else np.nan,
                "loss_lt10": float((hit["ret"] <= -0.10).mean()) if len(hit) else np.nan,
                "tail_gt20": float((hit["ret"] >= 0.20).mean()) if len(hit) else np.nan,
            }
        )
    return pd.DataFrame(rows)


def run(events_csv: str, csv_dir: str, output_dir: str, lookahead: int, max_events: int) -> str:
    events = pd.read_csv(events_csv)
    for c in ["break_date", "buy_date", "future_end_date"]:
        events[c] = pd.to_datetime(events[c], errors="coerce")
    events = events.dropna(subset=["symbol", "break_date", "buy_date", "future_end_date"]).copy()
    if max_events > 0:
        events = events.head(max_events).copy()

    grouped = scan_symbol_files(csv_dir, events["symbol"].unique())
    cache: Dict[str, pd.DataFrame] = {}
    rows: List[Dict[str, object]] = []
    for sym, sub in events.groupby("symbol"):
        paths = grouped.get(str(sym), [])
        if not paths:
            continue
        k = cache.get(str(sym))
        if k is None:
            k = load_symbol(paths)
            cache[str(sym)] = k
        if k.empty:
            continue
        for _, ev in sub.iterrows():
            base_i = row_idx_on_or_after(k, pd.Timestamp(ev["buy_date"]))
            exit_i = row_idx_on_or_before(k, pd.Timestamp(ev["future_end_date"]))
            if base_i is None or exit_i is None:
                continue
            for name, entry_i in find_entries(ev, k, lookahead):
                rows.append(calc_trade(ev, k, entry_i, name, base_i, exit_i))

    trades = pd.DataFrame(rows)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    out_dir = os.path.join(output_dir, f"ma120_hold10_entry_abtest_{stamp}")
    os.makedirs(out_dir, exist_ok=True)

    summary = summarize(trades, len(events))
    y = pd.to_datetime(events["buy_date"]).dt.year
    period = pd.Series(
        np.select([y <= 2018, (y >= 2019) & (y <= 2022), y >= 2023], ["2014-2018", "2019-2022", "2023-2026"], default="other")
    )
    total_by_period = period.value_counts()
    stable = stability(trades, total_by_period)

    trades.to_csv(os.path.join(out_dir, "entry_trades.csv"), index=False, encoding="utf-8-sig")
    summary.to_csv(os.path.join(out_dir, "entry_summary.csv"), index=False, encoding="utf-8-sig")
    stable.to_csv(os.path.join(out_dir, "entry_stability.csv"), index=False, encoding="utf-8-sig")
    print(out_dir)
    print(summary.to_string(index=False))
    return out_dir


def main() -> None:
    parser = argparse.ArgumentParser(description="Entry AB test after clean MA120 hold10 events.")
    parser.add_argument("--events-csv", required=True)
    parser.add_argument("--csv-dir", default="/Users/water/abu/data/csv")
    parser.add_argument("--output-dir", default="/Users/water/mylearn/PycharmProjects/abu-master/cy_quant/output")
    parser.add_argument("--lookahead", type=int, default=20)
    parser.add_argument("--max-events", type=int, default=0)
    args = parser.parse_args()
    run(args.events_csv, args.csv_dir, args.output_dir, args.lookahead, args.max_events)


if __name__ == "__main__":
    main()
